def compute_result(score):
    h, a = score.split("-")
    h, a = int(h), int(a)
    if h > a: return "主胜"
    if h < a: return "客胜"
    return "平"

def build_rows():
    rows = []
    mid = 1
    for league, rnd, provider, matches in ROUNDS:
        src = f"{league} 2025-26 第{rnd}轮（来源：{provider}）"
        for home, away, score, date in matches:
            rows.append({
                "match_id": f"REAL_{mid:04d}",
                "home": home,
                "away": away,
                "league": league,
                "match_time": date,
                "result": compute_result(score),
                "score": score,
                "collected_at": COLLECTED,
                "source": src,
            })
            mid += 1
    return rows

def write_real_csv(rows):
    path = os.path.join(DATA_DIR, "matches_real.csv")
    cols = ["match_id","home","away","league","match_time","result","score","collected_at","source"]
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)
    return path, len(rows)

def reserve_demo_columns():
    """给演示 CSV 追加空的 result/score 列（P1 预留，待真实数据回填）。"""
    path = os.path.join(DATA_DIR, "matches_supplemented.csv")
    with open(path, "r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        old_cols = reader.fieldnames
        rows = list(reader)
    if "result" in old_cols or "score" in old_cols:
        return path, "already", old_cols
    new_cols = list(old_cols) + ["result", "score"]
    for r in rows:
        r["result"] = ""
        r["score"] = ""
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=new_cols)
        w.writeheader()
        w.writerows(rows)
    return path, len(rows), new_cols

